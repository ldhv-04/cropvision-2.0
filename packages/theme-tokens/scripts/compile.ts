// Node-only compiler: palettes/*.json -> css-variables.css, palettes.generated.ts, figma tokens. Not imported by apps.
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { SHADCN_TOKENS, TELEMETRY_TOKENS, type Palette } from '../src/types.ts';

export { SHADCN_TOKENS, TELEMETRY_TOKENS };

const HEX = /^#[0-9A-Fa-f]{6}$/;
const RGBA = /^rgba\(\s*\d{1,3}\s*,\s*\d{1,3}\s*,\s*\d{1,3}\s*,\s*(0|1|0?\.\d+)\s*\)$/;
const LENGTH = /^\d+(\.\d+)?(rem|px)$/;

/** Throws with the palette id and token name when a palette is incomplete or malformed. */
export function validatePalette(p: Palette): Palette {
  const where = (t: string) => `palette "${p.id}" token "${t}"`;
  for (const t of SHADCN_TOKENS) {
    const v = p.shadcn?.[t];
    if (v == null) throw new Error(`${where(t)} is missing`);
    if (t === 'radius' ? !LENGTH.test(v) : !HEX.test(v)) throw new Error(`${where(t)} has invalid value "${v}" (${t === 'radius' ? 'rem/px length' : '#RRGGBB'} required)`);
  }
  for (const t of TELEMETRY_TOKENS) {
    const v = p.telemetry?.[t];
    if (v == null) throw new Error(`${where(t)} is missing`);
    if (!HEX.test(v) && !RGBA.test(v)) throw new Error(`${where(t)} has invalid value "${v}" (#RRGGBB or rgba() required)`);
  }
  if (p.scheme !== 'light' && p.scheme !== 'dark') throw new Error(`palette "${p.id}" scheme must be light or dark`);
  return p;
}

export function loadPalettesFromDir(dir: string): Palette[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => validatePalette(JSON.parse(readFileSync(join(dir, f), 'utf8')) as Palette))
    .sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));
}

const channels = (hex: string) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(' ');
const HEADER = '/* GENERATED by packages/theme-tokens/scripts/compile-palettes.ts from palettes/*.json. Do not edit. */\n';

/** First palette is the default (`:root`); every palette is also reachable as `.theme-<id>`. */
export function compileCss(palettes: readonly Palette[]): string {
  const blocks = palettes.map((p, i) => {
    const lines = [`  color-scheme: ${p.scheme};`];
    for (const t of SHADCN_TOKENS) {
      lines.push(`  --${t}: ${p.shadcn[t]};`);
      if (t !== 'radius') lines.push(`  --${t}-rgb: ${channels(p.shadcn[t])};`);
    }
    for (const t of TELEMETRY_TOKENS) lines.push(`  --telemetry-${t}: ${p.telemetry[t]};`);
    return `${i === 0 ? ':root,\n' : ''}.theme-${p.id} {\n${lines.join('\n')}\n}\n`;
  });
  return HEADER + blocks.join('\n');
}

/** W3C design-token sets (Tokens Studio / Figma Variables import), one set per palette. */
export function compileFigmaTokens(palettes: readonly Palette[]): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const p of palettes) {
    out[p.id] = {
      shadcn: Object.fromEntries(SHADCN_TOKENS.map((t) => [t, { $value: p.shadcn[t], $type: t === 'radius' ? 'borderRadius' : 'color' }])),
      telemetry: Object.fromEntries(TELEMETRY_TOKENS.map((t) => [t, { $value: p.telemetry[t], $type: 'color' }])),
    };
  }
  out.$themes = palettes.map((p) => ({ id: p.id, name: p.name, selectedTokenSets: { [p.id]: 'enabled' } }));
  out.$metadata = { tokenSetOrder: palettes.map((p) => p.id) };
  return out;
}

/** Typed palette module for React Native / Skia, which cannot read CSS variables. */
export function compileTs(palettes: readonly Palette[]): string {
  return `${HEADER.replace('/*', '//').replace(' */', '')}import type { Palette } from './types';

export const PALETTES = ${JSON.stringify(palettes.map(({ $schema: _, ...p }: Palette & { $schema?: string }) => p), null, 2)} as const satisfies readonly Palette[];
`;
}
